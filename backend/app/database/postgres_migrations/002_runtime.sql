CREATE UNIQUE INDEX idx_background_one_operation ON background_tasks(device_id, kind)
    WHERE status = 'running' AND kind NOT LIKE 'analysis_%';

-- Dispatch history used SQLite julianday(): invalid legacy text is NULL and
-- offsetless values are UTC. Keep this behavior without casting bad history.
CREATE FUNCTION state_timestamp(value text) RETURNS timestamptz
LANGUAGE plpgsql STABLE STRICT SET timezone = 'UTC' AS $$
BEGIN
    RETURN value::timestamptz;
EXCEPTION WHEN invalid_datetime_format OR datetime_field_overflow THEN
    RETURN NULL;
END;
$$;
